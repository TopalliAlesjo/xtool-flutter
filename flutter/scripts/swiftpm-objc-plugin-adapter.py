#!/usr/bin/env python3
"""Wrap a CocoaPods-only Objective-C Flutter plugin in a local Swift package.

The Linux build compiles Runner and its plugins as one Swift package, so plugins
that ship only a .podspec (no ios/<name>/Package.swift) fail to link. This copies
the plugin out of the pub cache, adds a minimal Package.swift around its unchanged
ios/Classes sources, and points the app at the copy via pubspec_overrides.yaml.

    swiftpm-objc-plugin-adapter.py <flutter app dir> <plugin name> [--frameworks UIKit,...]

Run `flutter pub get` in the app first. Tested with open_filex 4.7.0 only; plugins
with Swift sources, resources or third-party pod dependencies need more than this.
"""
import argparse
import json
import shutil
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("app", type=Path)
parser.add_argument("plugin")
parser.add_argument("--frameworks", default="UIKit")
parser.add_argument("--min-ios", default="13")
parser.add_argument("--out", type=Path, help="default: <app>/build/plugin-adapters/<plugin>")
args = parser.parse_args()

app = args.app.resolve()
plugins = json.loads((app / ".flutter-plugins-dependencies").read_text())
entry = next((p for p in plugins["plugins"]["ios"] if p["name"] == args.plugin), None)
if entry is None:
    raise SystemExit(f"{args.plugin} is not an iOS plugin of {app}")
source = Path(entry["path"])
if (source / "ios" / args.plugin / "Package.swift").exists():
    raise SystemExit(f"{args.plugin} already ships a Swift package; no adapter needed")

classes = source / "ios" / "Classes"
objc = sorted(classes.glob("*.m"))
headers = sorted(classes.glob("*.h"))
if not objc or any(classes.glob("*.swift")):
    raise SystemExit("only plugins with Objective-C sources in ios/Classes are supported")

destination = (args.out or app / "build" / "plugin-adapters" / args.plugin).resolve()
if destination.exists():
    raise SystemExit(f"{destination} exists; remove it to regenerate")
shutil.copytree(source, destination)

package = destination / "ios" / args.plugin
target = package / "Sources" / args.plugin
(target / "include").mkdir(parents=True)
for path in objc:
    shutil.copy2(path, target / path.name)
for path in headers:
    shutil.copy2(path, target / "include" / path.name)

frameworks = ", ".join(f'.linkedFramework("{name}")' for name in args.frameworks.split(",") if name)
(package / "Package.swift").write_text(f'''// swift-tools-version: 5.9
// Generated by xtool-flutter swiftpm-objc-plugin-adapter.py; plugin sources unchanged.
import PackageDescription
let package = Package(
    name: "{args.plugin}",
    platforms: [.iOS(.v{args.min_ios})],
    products: [.library(name: "{args.plugin}", targets: ["{args.plugin}"])],
    targets: [.target(
        name: "{args.plugin}",
        publicHeadersPath: "include",
        cSettings: [.unsafeFlags(["-fobjc-arc"])],
        linkerSettings: [{frameworks}]
    )]
)
''')

overrides = app / "pubspec_overrides.yaml"
line = f"  {args.plugin}:\n    path: {destination}\n"
if overrides.exists():
    text = overrides.read_text()
    if args.plugin in text:
        raise SystemExit(f"{overrides} already overrides {args.plugin}; edit it by hand")
    if "dependency_overrides:" not in text:
        text += "\ndependency_overrides:\n"
    overrides.write_text(text.rstrip("\n") + "\n" + line)
else:
    overrides.write_text("dependency_overrides:\n" + line)

print(f"Adapter: {package}\nOverride written to {overrides}; run `flutter pub get` again.")
